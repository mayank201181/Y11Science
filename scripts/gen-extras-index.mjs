import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Regenerate lib/extras/index.ts from the lib/extras/*.ts files (each exports
// `export const extras: TopicExtras`).
const dir = join(process.cwd(), "lib", "extras");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();

const camelSafe = (f) => "e_" + f.replace(/\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_");

const imports = files
  .map((f) => `import { extras as ${camelSafe(f)} } from "./${f.replace(/\.ts$/, "")}";`)
  .join("\n");
const arr = files.map((f) => `  ${camelSafe(f)},`).join("\n");

const content = `import type { TopicExtras } from "../types";
// AUTO-GENERATED by scripts/gen-extras-index.mjs — do not edit by hand.
${imports}

export const EXTRAS_LIST: TopicExtras[] = [
${arr}
];
`;

writeFileSync(join(dir, "index.ts"), content);
console.log("extras index written with", files.length, "entries");
